GAME.Chronicle = {

    /* ---------- 取某个 tag 的文本池 ---------- */
    pool: function (tag) {
        var all = GAME.DATA.CHRONICLE || {};
        var list = all[tag];
        return (list && list.length) ? list : null;
    },

    /* ---------- 纯抽样：返回一段文本，不写日志、不改玩家状态以外的东西 ----------
     * 同 tag 已抽过的条目不重复；整池抽完一轮后重开（再抽仍不越出本池）。
     * 返回 null 表示该 tag 无文本（调用方须容错）。 */
    surface: function (tag, p) {
        p = p || GAME.State.p();
        var list = this.pool(tag);
        if (!list) return null;
        if (!p.chronicleSeen) p.chronicleSeen = {};
        var used = p.chronicleSeen[tag] || [];
        var avail = [], i;
        for (i = 0; i < list.length; i++) {
            if (used.indexOf(i) < 0) avail.push(i);
        }
        if (!avail.length) { used = []; avail = []; for (i = 0; i < list.length; i++) avail.push(i); }
        var pick = avail[Math.floor(Math.random() * avail.length)];
        used.push(pick);
        p.chronicleSeen[tag] = used;
        return list[pick];
    },

    /* ---------- 抽样并写入见闻录（UI.log 仍是唯一文本出口） ---------- */
    narrate: function (tag, p) {
        var t = this.surface(tag, p);
        if (!t) return null;
        if (GAME.UI && GAME.UI.log) GAME.UI.log(t, "story");
        return t;
    },

    /* ---------- 某 tag 是否还剩未抽过的条目（UI 提示用） ---------- */
    remaining: function (tag, p) {
        p = p || GAME.State.p();
        var list = this.pool(tag);
        if (!list) return 0;
        var used = (p.chronicleSeen && p.chronicleSeen[tag]) || [];
        return Math.max(0, list.length - used.length);
    },
};
